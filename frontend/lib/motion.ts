/** Stable motion assignment so a product keeps its signature across routes. */
export function motionIndex(seed: string): number {
  let hash = 2166136261;
  for (let index = 0; index < seed.length; index += 1) {
    hash ^= seed.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0) % 320 + 1;
}
